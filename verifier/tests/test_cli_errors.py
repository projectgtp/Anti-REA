#!/usr/bin/env python3
"""Unit tests for CLI / verifier error handling (Agent B).

Every bad input must fail with a clear human message and a non-zero
exit — never an unhandled traceback. Proves, with no APK build and
no external tools except the CLI itself:
  * malformed YAML, unknown layer id, PARTIAL layer in enable
    (named PARTIAL, not PLANNED), wrong-typed config section, missing
    config file, missing input APK, missing source dir — all exit 2
    via anti-rea.py main() with "ERROR:" and no "Traceback".
  * `layers --list` still works and reports 103 layers.
  * attack.py with a missing --needles-file, tamper.py with a missing
    APK / non-ASCII blob / non-ZIP input, sigcheck.py on a non-APK —
    all exit non-zero with "ERROR" and no "Traceback".
  * sigcheck.py --json on two APKs prints one parseable JSON array
    (not two concatenated objects).

The anti-rea.py cases run main() in-process with the self-check
monkeypatched to pass: the manifest is regenerated by the
coordinator at the end of the v1.0 run, so the live CLI refuses
until then for hash reasons only — these tests isolate the
error-handling logic under test, not the manifest gate.

Usage:
  python3 verifier/tests/test_cli_errors.py
Exit 0 on pass, non-zero on any failure. Python stdlib only.
"""
import contextlib
import importlib.util
import io
import json
import subprocess
import sys
import tempfile
import unittest
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
V10 = HERE.parent.parent
TMP_BASE = Path("/home/hatch/tmp")


def _load_cli():
    spec = importlib.util.spec_from_file_location("antirea_cli",
                                                  str(V10 / "anti-rea.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    # Isolate from the manifest gate (see module docstring).
    mod.verify_self_check = lambda root=None: (True, [])
    return mod


CLI = _load_cli()


def run_cli(argv):
    """Run anti-rea.py main() in-process; return (rc, stdout, stderr)."""
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        rc = CLI.main(argv)
    return rc, out.getvalue(), err.getvalue()


class TestCliErrors(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="antirea-err-",
                                         dir=str(TMP_BASE)))
        self.addCleanup(lambda: __import__("shutil").rmtree(
            self.tmp, ignore_errors=True))

    def _cfg(self, text, name="bad.yaml"):
        p = self.tmp / name
        p.write_text(text, encoding="utf-8")
        return str(p)

    def assert_clean_fail(self, rc, out, err, needle=""):
        self.assertNotEqual(rc, 0, "expected non-zero exit, got 0: %s" % out)
        self.assertNotIn("Traceback", out + err,
                         "unhandled traceback in output")
        self.assertIn("ERROR", err, "no clear ERROR message on stderr: %r"
                      % err)
        if needle:
            self.assertIn(needle, err)

    def test_malformed_yaml(self):
        cfg = self._cfg("version: 1\nprotect:\n  strings: [unclosed\n")
        rc, out, err = run_cli(["protect", "--apk", "x.apk",
                                "--config", cfg, "--out", "o.apk"])
        self.assert_clean_fail(rc, out, err)

    def test_missing_config_file(self):
        rc, out, err = run_cli(["protect", "--apk", "x.apk",
                                "--config", str(self.tmp / "nope.yaml"),
                                "--out", "o.apk"])
        self.assert_clean_fail(rc, out, err, "cannot read config")

    def test_unknown_layer(self):
        cfg = self._cfg("version: 1\nlayers:\n  enable: [L01, L999]\n")
        rc, out, err = run_cli(["protect", "--apk", "x.apk",
                                "--config", cfg, "--out", "o.apk"])
        self.assert_clean_fail(rc, out, err, "unknown layer")

    def test_planned_layer_named_planned(self):
        # L100 is IMPLEMENTED; use a PARTIAL id's sibling check via
        # a made-up in-range id is impossible — registry has 0
        # PLANNED, so enable of a PARTIAL id is the live case (next
        # test). Here: L42 is implemented, L15 is partial.
        cfg = self._cfg("version: 1\nlayers:\n  enable: [L01]\n")
        rc, out, err = run_cli(["protect", "--apk", "x.apk",
                                "--config", cfg, "--out", "o.apk"])
        # L01-only config is valid; it fails later on the missing
        # APK, still cleanly and non-zero.
        self.assert_clean_fail(rc, out, err, "input APK not found")

    def test_partial_layer_named_partial(self):
        for lid in ("L15", "L60", "L91", "L98"):
            cfg = self._cfg("version: 1\nlayers:\n  enable: [%s]\n" % lid)
            rc, out, err = run_cli(["protect", "--apk", "x.apk",
                                    "--config", cfg, "--out", "o.apk"])
            self.assert_clean_fail(rc, out, err, "PARTIAL")
            self.assertNotIn("PLANNED", err,
                             "PARTIAL layer misreported as PLANNED: %s" % lid)

    def test_bare_key_parses_as_unset(self):
        # The YAML-subset parser turns a bare `enable:` into {} —
        # the project's own tests/testapp.yaml relies on it. The
        # validator must treat that as unset, not a type error.
        CLI._validate_config(
            CLI.load_config(str(V10 / "tests" / "testapp.yaml")))
        cfg = self._cfg("version: 1\nprotect:\n  strings:\n"
                        "layers:\n  enable:\n")
        CLI._validate_config(CLI.load_config(cfg))

    def test_wrong_typed_section(self):
        cfg = self._cfg("version: 1\nprotect: just-a-string\n")
        rc, out, err = run_cli(["protect", "--apk", "x.apk",
                                "--config", cfg, "--out", "o.apk"])
        self.assert_clean_fail(rc, out, err, "protect")

    def test_wrong_typed_list(self):
        cfg = self._cfg("version: 1\nprotect:\n  strings: not-a-list\n")
        rc, out, err = run_cli(["protect", "--apk", "x.apk",
                                "--config", cfg, "--out", "o.apk"])
        self.assert_clean_fail(rc, out, err, "protect.strings")

    def test_missing_apk(self):
        cfg = self._cfg("version: 1\nprotect:\n  strings: []\n")
        rc, out, err = run_cli(["protect", "--apk",
                                str(self.tmp / "nope.apk"),
                                "--config", cfg, "--out", "o.apk"])
        self.assert_clean_fail(rc, out, err, "input APK not found")

    def test_missing_source_dir(self):
        cfg = self._cfg("version: 1\n")
        rc, out, err = run_cli(["protect", "--source",
                                str(self.tmp / "no-src"),
                                "--config", cfg, "--out", "o-dir"])
        self.assert_clean_fail(rc, out, err, "source dir not found")

    def test_verify_missing_apk(self):
        cfg = self._cfg("version: 1\n")
        rc, out, err = run_cli(["verify", "--apk",
                                str(self.tmp / "nope.apk"),
                                "--config", cfg])
        self.assert_clean_fail(rc, out, err, "APK not found")

    def test_layers_list(self):
        rc, out, err = run_cli(["layers", "--list"])
        self.assertEqual(rc, 0, "layers --list failed: %s" % err)
        self.assertIn("L01", out)
        self.assertIn("total=103", out)


def _run(argv):
    p = subprocess.run([sys.executable, *argv], capture_output=True,
                       text=True, timeout=120)
    return p.returncode, p.stdout, p.stderr


class TestVerifierErrors(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="antirea-verr-",
                                         dir=str(TMP_BASE)))
        self.addCleanup(lambda: __import__("shutil").rmtree(
            self.tmp, ignore_errors=True))
        self.apk = self.tmp / "fake.apk"
        with zipfile.ZipFile(self.apk, "w") as z:
            z.writestr("classes.dex", b"dex\n035\x00" + b"\x00" * 200)
        self.not_apk = self.tmp / "plain.txt"
        self.not_apk.write_text("this is not an apk", encoding="utf-8")

    def assert_clean_fail(self, rc, out, err):
        self.assertNotEqual(rc, 0)
        self.assertNotIn("Traceback", out + err)

    def test_attack_missing_needles_file(self):
        rc, out, err = _run([str(V10 / "verifier" / "attack.py"),
                             "--control", str(self.apk),
                             "--protected", str(self.apk),
                             "--needles-file", str(self.tmp / "nope.txt")])
        self.assert_clean_fail(rc, out, err)
        self.assertIn("ERROR", err)
        self.assertEqual(rc, 2)

    def test_attack_missing_apk(self):
        rc, out, err = _run([str(V10 / "verifier" / "attack.py"),
                             "--control", str(self.tmp / "nope.apk"),
                             "--protected", str(self.apk),
                             "--needles", "x"])
        self.assert_clean_fail(rc, out, err)
        self.assertEqual(rc, 2)

    def test_tamper_missing_apk(self):
        rc, out, err = _run([str(V10 / "verifier" / "tamper.py"),
                             "--apk", str(self.tmp / "nope.apk"),
                             "--blob-b64", "QUJD",
                             "--out", str(self.tmp / "o.apk")])
        self.assert_clean_fail(rc, out, err)
        self.assertEqual(rc, 2)

    def test_tamper_non_ascii_blob(self):
        rc, out, err = _run([str(V10 / "verifier" / "tamper.py"),
                             "--apk", str(self.apk),
                             "--blob-b64", "héllo",
                             "--out", str(self.tmp / "o.apk")])
        self.assert_clean_fail(rc, out, err)
        self.assertIn("ASCII", err)
        self.assertEqual(rc, 2)

    def test_tamper_non_zip(self):
        rc, out, err = _run([str(V10 / "verifier" / "tamper.py"),
                             "--apk", str(self.not_apk),
                             "--blob-b64", "QUJD",
                             "--out", str(self.tmp / "o.apk")])
        self.assert_clean_fail(rc, out, err)
        self.assertEqual(rc, 2)

    def test_tamper_short_blob(self):
        rc, out, err = _run([str(V10 / "verifier" / "tamper.py"),
                             "--apk", str(self.apk),
                             "--blob-b64", "QU",
                             "--out", str(self.tmp / "o.apk")])
        self.assert_clean_fail(rc, out, err)
        self.assertEqual(rc, 2)

    def test_sigcheck_non_apk(self):
        rc, out, err = _run([str(V10 / "verifier" / "sigcheck.py"),
                             str(self.not_apk)])
        self.assert_clean_fail(rc, out, err)
        self.assertEqual(rc, 2)

    def test_sigcheck_json_array_two_targets(self):
        # Two targets only happen via --self-test (one positional APK
        # is the CLI shape). Unsigned fake APKs would exit 2, so use
        # the real self-test pair: both signed, exit 0, and the JSON
        # must parse as an ARRAY of two results (not two concatenated
        # objects, which was the old bug).
        rc, out, err = _run([str(V10 / "verifier" / "sigcheck.py"),
                             "--json", "--self-test"])
        self.assertEqual(rc, 0, "unexpected rc: %s %s" % (out, err))
        parsed = json.loads(out)
        self.assertIsInstance(parsed, list)
        self.assertEqual(len(parsed), 2)
        self.assertTrue(all(p["signing_block_found"] for p in parsed))

    def test_sigcheck_json_single_target_is_object(self):
        rc, out, err = _run([str(V10 / "verifier" / "sigcheck.py"),
                             "--json", str(self.apk)])
        parsed = json.loads(out)
        self.assertIsInstance(parsed, dict)


if __name__ == "__main__":
    unittest.main(verbosity=2)
