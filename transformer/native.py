#!/usr/bin/env python3
"""Anti-REA v1.0 — native / build-time helpers (Python stdlib only).

Three layers live here (smali-level transforms stay in smali.py):

  L08  R8 rename mapping: generate_r8_rules() emits a ProGuard/R8
       rules file from the config. R8 runs at BUILD time on the app's
       own classes — the CLI cannot rename classes in an already-built
       APK, so the rules must be applied in the app's Gradle build.
       The file keeps com.appcore.runtime.* unrenamed (the CLI-injected
       smali calls ReaRuntime by its exact class name) and repackages
       everything else R8 renames.

  L12  Native string hide: scan_elf_strings() finds printable strings
       in the PROGBITS+ALLOC sections of an ELF .so, and
       hide_elf_strings() replaces listed ones with a same-length XOR
       of a per-build key. SAME LENGTH ONLY: offsets, section headers
       and file size never change. A needle is replaced ONLY when it
       equals one complete maximal printable run — a needle that is a
       substring of a longer run, or a suffix shared with another
       string, is skipped, never partially rewritten. The replaced
       bytes are hidden at rest; nothing in the .so decrypts them, so
       ONLY strings the developer attests are inert at runtime (version
       banners, debug labels, never format strings / paths / symbols)
       may be listed. Replacing a string the native code actually uses
       breaks the .so — that is a documented misuse, not a bug.

  L13  Asset encrypt: encrypt_asset_bytes() / decrypt_asset_bytes()
       are the BYTE form of the crypto.py blob format (raw =
       sha256(plain) || plain, XOR with a 32-byte split key, key =
       part1 XOR part2). An encrypted asset file is the raw cipher
       bytes (32 bytes longer than the plaintext). The Kotlin side is
       runtime/ReaAssets.kt; key parts belong in the REA-IR manifest,
       never in the asset file itself.

Honest limits: L08 renames are only as strong as R8 itself (a
determined analyst can still read renamed code); L12 hides bytes from
`strings`, it does not stop a runtime dump; L13 is the same XOR +
split-key obfuscation as L01, not strong crypto.
"""
import base64
import hashlib
import re
import secrets
import struct

KEY_LEN = 32

# ---------------------------------------------------------------- L08
RUNTIME_KEEP_CLASSES = [
    "com.appcore.runtime.ReaRuntime",
    "com.appcore.runtime.ReaGuardProvider",
    "com.appcore.runtime.ReaEnv",
    "com.appcore.runtime.ReaIntegrity",
    "com.appcore.runtime.ReaTraps",
    "com.appcore.runtime.ReaModBlock",
    "com.appcore.runtime.ReaTrace",
    "com.appcore.runtime.ReaMemory",
    "com.appcore.runtime.ReaRepack",
    "com.appcore.runtime.ReaNative",
    "com.appcore.runtime.ReaAssets",
]


def generate_r8_rules(config):
    """Build the text of a ProGuard/R8 rules file (L08).

    config is the loaded anti-rea.yaml dict. Optional keys:
      app.package      — app package; repackaging target is
                         "<package>.rea" when known, "" (default
                         package) otherwise.
      r8.keep          — extra class names to -keep (default: none;
                         the runtime classes above are always kept).
      r8.repackage     — explicit -repackageclasses argument.
      r8.allow_access_modification — bool, default True.

    The returned text documents that it MUST be applied in the app's
    own Gradle build (proguardFiles in the release buildType) and
    does nothing on an already-built APK.
    """
    cfg = config or {}
    app = cfg.get("app") or {}
    package = (app.get("package") or "").strip()
    r8 = cfg.get("r8") or {}
    extra_keep = list(r8.get("keep") or [])
    repackage = r8.get("repackage")
    if repackage is None:
        repackage = ("%s.rea" % package) if package else ""
    allow_access = r8.get("allow_access_modification", True)

    lines = []
    lines.append("# Anti-REA v1.0 — L08 generated R8 / ProGuard rules.")
    lines.append("# Generated by transformer/native.py generate_r8_rules().")
    lines.append("#")
    lines.append("# HOW TO APPLY (the app's own Gradle build — REQUIRED):")
    lines.append("#   copy this file to app/proguard-rules-appcore.pro and add")
    lines.append("#     proguardFiles getDefaultProguardFile(")
    lines.append("#         'proguard-android-optimize.txt'),")
    lines.append("#         'proguard-rules.pro', 'proguard-rules-appcore.pro'")
    lines.append("#   to the release buildType. R8 runs at BUILD time on the")
    lines.append("#   app's classes; the anti-rea CLI CANNOT rename classes in")
    lines.append("#   an already-built APK, so these rules do nothing if they")
    lines.append("#   are only added after the APK exists. Protect with the CLI")
    lines.append("#   AFTER the R8 build, on the already-obfuscated APK.")
    lines.append("#")
    lines.append("# The anti-rea runtime MUST NOT be renamed: the CLI-injected")
    lines.append("# smali calls com.appcore.runtime.ReaRuntime (and the other")
    lines.append("# runtime classes) by exact class name, and the manifest")
    lines.append("# names ReaGuardProvider by exact class name. Keep them all.")
    for cls in RUNTIME_KEEP_CLASSES:
        lines.append("-keep class %s { *; }" % cls)
    lines.append("-keep class com.appcore.runtime.** { *; }")
    for cls in extra_keep:
        lines.append("-keep class %s { *; }" % cls)
    lines.append("# Obfuscate the app's own classes: repackage everything R8")
    lines.append("# renames into one package so original package structure")
    lines.append("# (which leaks feature names) does not survive the build.")
    lines.append("-repackageclasses '%s'" % repackage)
    if allow_access:
        lines.append("-allowaccessmodification")
    lines.append("# NOTE: Android entry points (Activities, Services,")
    lines.append("# Receivers, Providers) are kept by the app's own")
    lines.append("# proguard-rules.pro / the default Android rules, not here.")
    lines.append("# Do NOT add -keep for app classes here: renamed app code")
    lines.append("# is the protection; keeping it defeats L08.")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- L12
_PRINTABLE = set(range(0x20, 0x7F))

SHT_PROGBITS = 1
SHF_ALLOC = 0x2


class ElfError(ValueError):
    pass


def parse_elf_sections(data):
    """Minimal ELF section parser (stdlib only).

    Returns a list of dicts {name, type, flags, offset, size} for every
    section header. Supports 32/64-bit little-endian ELF (what Android
    ships). Raises ElfError on anything else — never guesses.
    """
    if len(data) < 52 or data[:4] != b"\x7fELF":
        raise ElfError("not an ELF file (bad magic)")
    ei_class = data[4]
    ei_data = data[5]
    if ei_data != 1:
        raise ElfError("only little-endian ELF is supported")
    if ei_class == 2:  # 64-bit
        if len(data) < 64:
            raise ElfError("truncated ELF64 header")
        e_shoff, = struct.unpack_from("<Q", data, 0x28)
        e_shentsize, e_shnum, e_shstrndx = struct.unpack_from("<HHH", data, 0x3A)
        fmt, size = "<IIQQQQIIQQ", 64
    elif ei_class == 1:  # 32-bit
        if len(data) < 52:
            raise ElfError("truncated ELF32 header")
        e_shoff, = struct.unpack_from("<I", data, 0x20)
        e_shentsize, e_shnum, e_shstrndx = struct.unpack_from("<HHH", data, 0x2E)
        fmt, size = "<IIIIIIIIII", 40
    else:
        raise ElfError("unknown ELF class %d" % ei_class)
    if e_shentsize < size:
        raise ElfError("section header size %d < %d" % (e_shentsize, size))
    if e_shoff == 0 or e_shnum == 0:
        raise ElfError("ELF has no section headers")
    if e_shoff + e_shnum * e_shentsize > len(data):
        raise ElfError("section headers run past end of file")
    raw_sections = []
    for i in range(e_shnum):
        off = e_shoff + i * e_shentsize
        vals = struct.unpack_from(fmt, data, off)
        if ei_class == 2:
            (sh_name, sh_type, sh_flags, _addr, sh_offset,
             sh_size) = vals[0], vals[1], vals[2], vals[3], vals[4], vals[5]
        else:
            (sh_name, sh_type, sh_flags, _addr, sh_offset,
             sh_size) = vals[0], vals[1], vals[2], vals[3], vals[4], vals[5]
        raw_sections.append({
            "name_off": sh_name, "type": sh_type, "flags": sh_flags,
            "offset": sh_offset, "size": sh_size})
    # Resolve names from the section-header string table.
    if e_shstrndx < len(raw_sections):
        strtab = raw_sections[e_shstrndx]
        base, end = strtab["offset"], strtab["offset"] + strtab["size"]
        table = data[base:end] if end <= len(data) else b""

        def _name(noff):
            if noff >= len(table):
                return ""
            stop = table.find(b"\x00", noff)
            if stop < 0:
                stop = len(table)
            return table[noff:stop].decode("ascii", "replace")
    else:
        _name = lambda noff: ""
    for s in raw_sections:
        s["name"] = _name(s["name_off"])
        del s["name_off"]
    return raw_sections


def scan_elf_strings(data, min_len=4):
    """Find printable strings in PROGBITS+ALLOC sections.

    Returns a list of (offset, string) for every MAXIMAL printable run
    of length >= min_len. A run is bounded by non-printable bytes on
    both sides, so a string that is a suffix of a longer stored string
    appears only as part of that longer run — never as its own entry.
    Offsets are file offsets, so a same-length replacement never moves
    anything.
    """
    sections = parse_elf_sections(data)
    found = []
    for s in sections:
        if s["type"] != SHT_PROGBITS or not (s["flags"] & SHF_ALLOC):
            continue
        start, end = s["offset"], s["offset"] + s["size"]
        if end > len(data):
            continue
        chunk = data[start:end]
        i = 0
        n = len(chunk)
        while i < n:
            if chunk[i] in _PRINTABLE:
                j = i
                while j < n and chunk[j] in _PRINTABLE:
                    j += 1
                if j - i >= min_len:
                    found.append((start + i, chunk[i:j].decode("ascii")))
                i = j
            else:
                i += 1
    return found


def hide_elf_strings(data, needles, key=None):
    """Same-length XOR replacement of listed strings in an ELF .so.

    needles: iterable of exact strings to hide. A needle is replaced
    ONLY when it equals one complete maximal printable run found by
    scan_elf_strings(); anything else is reported as skipped with a
    reason (substring-of-a-longer-run, suffix-shared, or not found).
    The replacement is the needle bytes XORed with a fresh random
    32-byte key (repeating); the NUL terminator, if any, is never
    touched, and no offset or length changes anywhere in the file.

    Returns (new_data, report) where report has:
      replaced: [{string, offset, length, sha256}]
      skipped:  [{string, reason}]
      key_part1_b64 / key_part2_b64: the split key (record in REA-IR)
      changed_bytes: total bytes rewritten
    The input bytes are never modified in place.
    """
    if key is None:
        key = secrets.token_bytes(KEY_LEN)
    part1 = secrets.token_bytes(KEY_LEN)
    part2 = bytes(a ^ b for a, b in zip(key, part1))
    runs = scan_elf_strings(data)
    by_text = {}
    for off, text in runs:
        by_text.setdefault(text, []).append(off)
    out = bytearray(data)
    report = {
        "replaced": [],
        "skipped": [],
        "key_part1_b64": base64.b64encode(part1).decode("ascii"),
        "key_part2_b64": base64.b64encode(part2).decode("ascii"),
        "changed_bytes": 0,
    }
    for needle in needles:
        if not needle:
            continue
        offs = by_text.get(needle)
        if not offs:
            # Distinguish "not present at all" from "present only as
            # part of a longer run" — the second case is the
            # suffix-shared / substring case the scanner refuses.
            present = any(needle in text for _, text in runs)
            report["skipped"].append({
                "string": needle,
                "reason": ("substring of a longer stored run — refusing "
                           "partial rewrite" if present else
                           "not found in PROGBITS+ALLOC sections"),
            })
            continue
        raw = needle.encode("ascii")
        for off in offs:
            cipher = bytes(b ^ key[i % KEY_LEN]
                           for i, b in enumerate(raw))
            out[off:off + len(raw)] = cipher
            report["replaced"].append({
                "string": needle,
                "offset": off,
                "length": len(raw),
                "sha256": hashlib.sha256(raw).hexdigest(),
            })
            report["changed_bytes"] += len(raw)
    return bytes(out), report


def verify_elf_unchanged_except(before, after, allowed_ranges):
    """Check two ELF files differ ONLY inside allowed (offset, length)
    ranges and that section headers still parse identically.

    Returns a list of problems (empty = clean). Used by the L12 test
    to prove a same-length replacement moved nothing else.
    """
    problems = []
    if len(before) != len(after):
        problems.append("file size changed: %d -> %d"
                        % (len(before), len(after)))
        return problems
    try:
        sec_before = parse_elf_sections(before)
        sec_after = parse_elf_sections(after)
    except ElfError as e:
        problems.append("ELF no longer parses: %s" % e)
        return problems
    if sec_before != sec_after:
        problems.append("section headers changed")
    diff = [i for i in range(len(before)) if before[i] != after[i]]
    allowed = set()
    for off, length in allowed_ranges:
        allowed.update(range(off, off + length))
    outside = [i for i in diff if i not in allowed]
    if outside:
        problems.append("%d changed bytes outside allowed ranges "
                        "(first: %d)" % (len(outside), outside[0]))
    return problems


# ---------------------------------------------------------------- L13
def encrypt_asset_bytes(data):
    """Encrypt asset bytes (L13) — the BYTE form of the crypto.py blob
    format: raw = sha256(plain) || plain, XOR with a fresh random
    32-byte key, key = part1 XOR part2. Returns dict with blob_bytes
    (raw cipher bytes, len(plain)+32), key parts (base64), and hashes.
    Mirrors runtime/ReaAssets.kt decryptAsset() exactly."""
    if not isinstance(data, (bytes, bytearray)):
        raise TypeError("asset data must be bytes")
    plain = bytes(data)
    key = secrets.token_bytes(KEY_LEN)
    part1 = secrets.token_bytes(KEY_LEN)
    part2 = bytes(a ^ b for a, b in zip(key, part1))
    raw = hashlib.sha256(plain).digest() + plain
    cipher = bytes(b ^ key[i % KEY_LEN] for i, b in enumerate(raw))
    return {
        "blob_bytes": cipher,
        "key_part1_b64": base64.b64encode(part1).decode("ascii"),
        "key_part2_b64": base64.b64encode(part2).decode("ascii"),
        "blob_sha256": hashlib.sha256(cipher).hexdigest(),
        "plain_sha256": hashlib.sha256(plain).hexdigest(),
    }


def decrypt_asset_bytes(cipher, part1_b64, part2_b64):
    """Reference decryptor (mirrors ReaAssets.decryptAsset). Raises
    ValueError on any integrity failure; never returns wrong bytes."""
    cipher = bytes(cipher)
    p1 = base64.b64decode(part1_b64)
    p2 = base64.b64decode(part2_b64)
    if len(p1) != len(p2):
        raise ValueError("Anti-REA: key parts have different lengths")
    key = bytes(a ^ b for a, b in zip(p1, p2))
    raw = bytes(b ^ key[i % KEY_LEN] for i, b in enumerate(cipher))
    if len(raw) <= 32:
        raise ValueError("Anti-REA: payload too short")
    expected, plain = raw[:32], raw[32:]
    if hashlib.sha256(plain).digest() != expected:
        raise ValueError("Anti-REA: payload integrity check failed")
    return plain


def encrypt_asset_file(path, stats=None):
    """Encrypt one asset file in place (L13). The file content is
    replaced by the raw cipher bytes. Returns the encrypt dict plus
    the file path, or None when the file does not exist. stats (dict,
    optional) is updated with assets_encrypted / asset_bytes_in/out.
    """
    from pathlib import Path
    p = Path(path)
    if not p.is_file():
        return None
    plain = p.read_bytes()
    enc = encrypt_asset_bytes(plain)
    p.write_bytes(enc["blob_bytes"])
    enc["path"] = str(p)
    enc["plain_size"] = len(plain)
    if stats is not None:
        stats["assets_encrypted"] = stats.get("assets_encrypted", 0) + 1
        stats["asset_plain_bytes"] = stats.get("asset_plain_bytes", 0) + len(plain)
        stats["asset_blob_bytes"] = stats.get("asset_blob_bytes", 0) + len(enc["blob_bytes"])
    return enc


def asset_entries_from_config(config):
    """Asset paths to encrypt, from config. Accepts a top-level
    `assets:` list, or `protect.assets:` — both optional, default []."""
    cfg = config or {}
    entries = list(cfg.get("assets") or [])
    protect = cfg.get("protect") or {}
    entries.extend(protect.get("assets") or [])
    return entries
