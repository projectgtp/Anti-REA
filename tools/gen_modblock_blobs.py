#!/usr/bin/env python3
"""Generate runtime/ModBlockData.kt — the L101 blocklist as encrypted blobs.

The plaintext package names live ONLY in layers/MT-LIKE-BLOCKLIST.md
(and in this generator script, which is a build tool — it is NOT
shipped inside a protected APK). The generated .kt file contains
base64 XOR blobs + split key parts only, so `grep` for a package
name over runtime/*.kt or the protected dex finds nothing.

Usage:  python3 tools/gen_modblock_blobs.py
Run it again ONLY when the blocklist changes (fresh random keys
every run — that is per-build rotation working as designed).

Do NOT edit ModBlockData.kt by hand; regenerate it with this script.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HERE / "transformer"))
from crypto import encrypt_payload  # noqa: E402

# Must match layers/MT-LIKE-BLOCKLIST.md enforced table EXACTLY.
# GameGuardian is deliberately NOT here (UNVERIFIED, see the .md).
BLOCKED_PACKAGES = [
    "bin.mt.plus",                      # 1  MT Manager
    "bin.mt.plus.canary",               # 2  MT Manager clone/canary
    "bin.mt.plus-org",                  # 3  MT Manager older variant
    "ru.maximoff.apktool",              # 4  Apktool M
    "ru.maximoff.apktool.unapkm",       # 5  Apktool M UnApkm
    "com.gmail.heagoo.apkeditor",       # 6  APK Editor
    "com.gmail.heagoo.apkeditor.pro",   # 7  APK Editor Pro
    "com.wn.app.np",                    # 8  NP Manager
    "com.metube.arshi",                 # 9  "NP Manager" per APKPure (conflict noted)
    "io.github.abdurazaaqmohammed.MPManager",  # 10 MP-Manager
    "com.apkmanager",                   # 11 APK Manager
    "com.chelpus.lackypatch",           # 12 Lucky Patcher (spelling is correct)
    "ru.aaaaaaci.installer",            # 13 Lucky Patcher Installer
]


def main():
    lines = []
    lines.append("package com.antirea.runtime")
    lines.append("")
    lines.append("/**")
    lines.append(" * L101 blocklist data — GENERATED, do not edit by hand.")
    lines.append(" * Generated by tools/gen_modblock_blobs.py from")
    lines.append(" * layers/MT-LIKE-BLOCKLIST.md. Each entry is one")
    lines.append(" * Triple(blob_b64, key_part1_b64, key_part2_b64) in the")
    lines.append(" * standard ReaRuntime blob format (sha256(plain) || plain,")
    lines.append(" * XOR with a 32-byte split key). Plaintext package names")
    lines.append(" * NEVER appear in this file — grep for them finds nothing.")
    lines.append(" * ReaModBlock.decrypts them in memory only, at runtime.")
    lines.append(" */")
    lines.append("internal object ModBlockData {")
    lines.append("    val BLOCKED: List<Triple<String, String, String>> = listOf(")
    for pkg in BLOCKED_PACKAGES:
        p = encrypt_payload(pkg)
        lines.append("        Triple(\"%s\", \"%s\", \"%s\"),"
                     % (p["blob_b64"], p["key_part1_b64"], p["key_part2_b64"]))
    lines.append("    )")
    lines.append("}")
    out = HERE / "runtime" / "ModBlockData.kt"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s (%d entries)" % (out, len(BLOCKED_PACKAGES)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
